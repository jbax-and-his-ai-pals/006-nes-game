"""Generate linker-visible fixed-engine symbols for banked scene modules."""

from pathlib import Path
import re
import sys


EXPORT_ENTRY = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s+([0-9A-Fa-f]{6})\s+R[LAZ]")
SCENE_STUBS = {
    "_run_neon_avenue",
    "_run_bar_interior",
    "_run_casino",
    "_run_mart_exterior",
    "_run_mart_interior",
    "_run_park",
    "_run_sewer",
    "_run_zoo",
    "_run_arcade_exterior",
    "_run_sidestreet_exterior",
}
SHARED_ZP = {"c_sp", "sreg", "ptr1", "ptr2", "ptr4", "tmp1", "tmp2"}


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_fixed_api.py FIXED_ENGINE.MAP OUTPUT.S")
        return 2

    source = Path(sys.argv[1])
    destination = Path(sys.argv[2])
    symbols: dict[str, int] = {}
    in_exports = False
    for line in source.read_text(encoding="ascii").splitlines():
        if line.startswith("Exports list by name:"):
            in_exports = True
            continue
        if in_exports and line.startswith("Exports list by value:"):
            break
        if not in_exports:
            continue
        for match in EXPORT_ENTRY.finditer(line):
            name, address = match.groups()
            # Scene entry points are owned by the scene module, never the
            # fixed validation stubs used to produce this map.
            if (name.startswith("_") or name in SHARED_ZP) and name not in SCENE_STUBS and name != "_main":
                symbols[name] = int(address, 16) & 0xFFFF

    if not symbols:
        print(f"{source}: no exported symbols found")
        return 1

    lines = [
        "; Generated by tools/gen_fixed_api.py. Do not edit.",
        "; These aliases let a $8000 scene call the fixed $C000 engine.",
    ]
    for name, address in sorted(symbols.items()):
        lines.append(f".export {name}")
        lines.append(f"{name} = ${address:04X}")
    destination.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Generated {len(symbols)} fixed API symbols: {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
